"""One FKC results table per log-weight clip rate (from clip_sweep/summary.csv).

Rows: Model (SSFM / Diffusion SDE) x NFE x FKC (N = K=1, no resampling, no
clip; Y = K particles resampled every step with the table's TOTAL clip rate).
Columns: Energy-W2, MMD, TV, W1, W2 as mean +- std over the valid seeds.
A row is reported only if every seed is valid; otherwise it is marked
diverged with the number of diverged seeds. The FKC=N rows do not depend on
the clip rate and are repeated in every table for reference.

Writes one CSV per clip rate and a LaTeX file (booktabs) with one table per
clip rate; in LaTeX the best value per (NFE, metric) is bolded.
"""

from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path

METRICS = (('energy_w2', 'Energy-W2', 3), ('mmd', 'MMD', 4), ('total_variation', 'TV', 3),
           ('w1', 'W1', 2), ('w2', 'W2', 2))
MODELS = (('learned', 'iSSFM'), ('diffusion', 'Diffusion SDE'))


def fmt(value: float, digits: int, scale: float | None = None) -> str:
    """Math-mode body: fixed-point, or ``a\\times10^{b}`` when ``scale`` >= 1e4."""
    reference = abs(value) if scale is None else scale
    if reference >= 1e4:
        mantissa, exponent = f'{value:.2e}'.split('e')
        return f'{mantissa}\\times10^{{{int(exponent)}}}'
    return f'{value:.{digits}f}'


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--summary', type=Path, default=Path('results/fkc/clip_sweep/summary.csv'))
    parser.add_argument('--k', type=int, default=8)
    parser.add_argument('--clips', type=float, nargs='+', default=[0.0, 0.10, 0.20, 0.25, 0.50, 0.75])
    parser.add_argument('--nfe', type=int, nargs='+', default=[4, 8, 12, 16, 20, 24, 32, 64])
    parser.add_argument('--out-dir', type=Path, default=Path('results/fkc/tables'))
    args = parser.parse_args()

    rows = list(csv.DictReader(args.summary.open()))

    def lookup(sampler: str, nfe: int, k: int, clip: float) -> dict | None:
        for row in rows:
            if (row['sampler'] == sampler and int(row['nfe']) == nfe and int(row['k']) == k
                    and abs(float(row['clip_total']) - clip) < 1e-9):
                return row
        return None

    args.out_dir.mkdir(parents=True, exist_ok=True)
    latex = [
        '% Generated by scripts/make_fkc_clip_tables.py. Requires \\usepackage{booktabs} and the',
        '% \\cmark / \\xmark macros, e.g. with \\usepackage{pifont}:',
        '%   \\newcommand{\\cmark}{\\ding{51}}  \\newcommand{\\xmark}{\\ding{55}}',
        f'% K={args.k} for FKC rows; mean with std as a subscript over seeds 0--3; lower is better.',
        '',
    ]
    for clip in args.clips:
        tag = f'clip{round(100 * clip):02d}'
        table = []
        for nfe in args.nfe:
            for sampler, name in MODELS:
                for fkc, k, c in (('N', 1, 0.0), ('Y', args.k, clip)):
                    row = lookup(sampler, nfe, k, c)
                    if row is None:
                        raise ValueError(f'missing {sampler} NFE={nfe} K={k} clip={c}')
                    total = int(row['total_seeds'])
                    valid = int(row['valid'])
                    entry = {'model': name, 'nfe': nfe, 'fkc': fkc, 'valid': valid, 'total': total}
                    for key, _, _ in METRICS:
                        entry[key] = (float(row[f'{key}_mean']), float(row[f'{key}_std'])) \
                            if valid == total else None
                    table.append(entry)

        with (args.out_dir / f'fkc_table_{tag}.csv').open('w', newline='') as file:
            writer = csv.writer(file)
            writer.writerow(['model', 'nfe', 'fkc', 'valid_seeds'] +
                            [f'{key}_{s}' for key, _, _ in METRICS for s in ('mean', 'std')])
            for e in table:
                cells = []
                for key, _, _ in METRICS:
                    cells += [f'{e[key][0]:.6g}', f'{e[key][1]:.6g}'] if e[key] else ['', '']
                writer.writerow([e['model'], e['nfe'], e['fkc'], f'{e["valid"]}/{e["total"]}'] + cells)

        best = {}
        for nfe in args.nfe:
            for key, _, _ in METRICS:
                values = [e[key][0] for e in table if e['nfe'] == nfe and e[key]]
                best[(nfe, key)] = min(values) if values else None
        clip_label = 'no clipping' if clip == 0 else f'{round(100 * clip)}\\% total log-weight clipping'
        latex += [
            '\\begin{table}[t]',
            '\\centering\\small',
            f'\\caption{{40 Gaussians, $\\beta=3$. FKC with $K={args.k}$, {clip_label}. '
            'Mean over 4 seeds (10k samples) with standard deviation as a subscript; lower is better; '
            'best per NFE in bold. $\\infty$: diverged. Rows without FKC are unclipped and '
            'identical across tables.}',
            f'\\label{{tab:fkc_{tag}}}',
            '\\begin{tabular}{llc' + 'c' * len(METRICS) + '}',
            '\\toprule',
            'Model & NFE & FKC & ' + ' & '.join(label for _, label, _ in METRICS) + ' \\\\',
            '\\midrule',
        ]
        for index, e in enumerate(table):
            cells = []
            for key, _, digits in METRICS:
                if e[key] is None:
                    # Reported only when all seeds are valid (the CSV keeps the count).
                    cells.append('$\\infty$')
                    continue
                mean, std = e[key]
                m_txt, s_txt = fmt(mean, digits), fmt(std, digits, scale=abs(mean))
                if best[(e['nfe'], key)] is not None and math.isclose(mean, best[(e['nfe'], key)]):
                    m_txt = f'\\mathbf{{{m_txt}}}'
                cells.append(f'${m_txt}_{{\\pm {s_txt}}}$')
            mark = '\\cmark' if e['fkc'] == 'Y' else '\\xmark'
            latex.append(f'{e["model"]} & {e["nfe"]} & {mark} & ' + ' & '.join(cells) + ' \\\\')
            if index % 4 == 3 and index != len(table) - 1:
                latex.append('\\midrule')
        latex += ['\\bottomrule', '\\end{tabular}', '\\end{table}', '']
        print(f'[tables] {tag}: {len(table)} rows')

    (args.out_dir / 'fkc_tables.tex').write_text('\n'.join(latex))
    print(f'[tables] wrote {args.out_dir}')


if __name__ == '__main__':
    main()
